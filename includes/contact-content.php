function mahaba_load_contact_content(PDO $pdo, array $defaults): array
{
    $content = $defaults;
    $statement = $pdo->query(
        "SELECT language, content_key, content_value FROM site_content WHERE content_key LIKE 'contact_%'"
    );

    foreach ($statement->fetchAll() as $row) {
        $field = substr($row['content_key'], strlen('contact_'));
        $language = $row['language'];
        if (!isset($content[$language][$field])) {
            continue;
        }

        $value = $row['content_value'];
        if ($field === 'email_address' && filter_var($value, FILTER_VALIDATE_EMAIL) === false) {
            error_log('Mahaba ignored invalid stored contact email address.');
            continue;
        }
        if (in_array($field, ['facebook_url', 'instagram_url'], true) && $value !== '') {
            $safeUrl = mahaba_safe_external_url($value);
            if ($safeUrl === null) {
                error_log('Mahaba ignored invalid stored social media URL.');
                continue;
            }
            $value = $safeUrl;
        }


        $content[$language][$field] = $value;
    }

    return $content;
}
