function site_escape(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function site_text(string $language, string $key): string
{
    global $siteTranslations;
    return $siteTranslations[$language][$key] ?? $siteTranslations['en'][$key] ?? $key;
}
